func (s *Server) routes() []ui.Route {
	rs := slices.Concat(s.Routes(), []ui.Route{
		{Pattern: "POST /certificate", Priv: ui.OrgAdmin, H: s.setCertificate},
	}, s.hostPageRoutes())
	if s.manager != nil {
		return append(rs, s.managerRoutes()...)
	}
	return append(rs, s.hostModeRoutes()...)
}

